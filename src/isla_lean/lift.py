"""Lift a code region into a Lean module in pcode-lean's step/Frame format."""

from __future__ import annotations

from .errors import Unsupported
from .footprint import EXECUTE_NOTE, STOP_NOTE, TraceSource
from .sexpr import parse
from .trace import Block, Region


def lift(name: str, code: bytes, base: int, source: TraceSource, jobs: int = 1) -> str:
    """Translate every 32-bit instruction of `code` at `base`; the entry is the first byte."""
    if not name.isidentifier() or not name[0].isupper():
        raise ValueError(f"module name must be a capitalized identifier: {name!r}")
    if not code or len(code) % 4:
        raise Unsupported("region must be a nonempty whole number of 32-bit instructions")
    pcs = [base + i for i in range(0, len(code), 4)]
    region = Region({pc: f"p{i}" for i, pc in enumerate(pcs)})
    if base + len(code) > 1 << 64:
        raise Unsupported("region wraps around the 64-bit address space")
    if hasattr(source, "prefetch"):
        source.prefetch([(code[pc - base : pc - base + 4], pc) for pc in pcs], jobs)
    blocks, cuts = [], []
    for pc in pcs:
        word = code[pc - base : pc - base + 4]
        if word[0] & 0b11 != 0b11:
            raise Unsupported(f"compressed instruction at {pc:#x}; assemble with -march=rv64i")
        text = source.footprint(word, pc)
        cuts += [f"--   {pc:#x}: {line[len(STOP_NOTE):].strip()}"
                 for line in text.splitlines() if line.startswith(STOP_NOTE)]
        _check_execute(text, pc)
        traces = [t for t in parse(text) if t[:1] == ["trace"]]
        if len(traces) != 1:
            raise Unsupported(f"expected one trace tree at {pc:#x}, got {len(traces)}")
        blocks.append((pc, word, Block(pc, region, word).translate(traces[0][1:])))

    lines = [
        "-- Generated by isla-lean from Isla footprints of the Sail RISC-V model.",
        *(f"-- {line}" for line in source.provenance()),
        f"-- Bytes at {base:#x}: {code.hex()}",
        "-- Environment assumptions read by the traces (not checked):",
        *(f"--   {a}" for a in sorted(region.assumptions)),
        "-- Executions cut from the model (their guards become `stuck` exits):",
        *(cuts or ["--   (none)"]),
        "import IslaLean.Basic",
        "",
        f"namespace {name}",
        "open IslaLean",
        "",
        "inductive PC where",
        *(f"  | {region.labels[pc]}" for pc in pcs),
        "  deriving DecidableEq, Repr",
        "",
        "abbrev Frame := PC × RVState",
        "",
        "def step (frame : Frame) : Id (Sum Frame Exit) := do",
        "  let s := frame.2",
        "  match frame.1 with",
    ]
    for pc, word, body in blocks:
        lines.append(f"  | .{region.labels[pc]} =>")
        lines.append(f"    -- {pc:#x}: {int.from_bytes(word, 'little'):08x}")
        lines.extend(body)
    lines += [
        "",
        f"def initial (s : RVState) : Frame := (.p0, {{ s with pc := 0x{base:x} }})",
        "def run (s : RVState) := IslaLean.run step (initial s)",
        "def execute (fuel : Nat) (s : RVState) := IslaLean.execute step fuel (initial s)",
        "",
        f"end {name}",
        "",
    ]
    return "\n".join(lines)


def _check_execute(text: str, pc: int) -> None:
    """Reject instructions whose `execute` does nothing on some path (not in the snapshot)."""
    notes = [line for line in text.splitlines() if line.startswith(EXECUTE_NOTE)]
    if not notes:
        return  # traces recorded without the probe (older caches) carry no evidence either way
    counts = [int(n) for n in notes[0][len(EXECUTE_NOTE):].strip(" []").split(",") if n.strip()]
    if not counts or 0 in counts:
        raise Unsupported(f"instruction at {pc:#x}: execute performs no events on some path "
                          "(not implemented by this model snapshot, or only a cut trap path)")
